import { Command } from "commander";
import { select } from "@inquirer/prompts";
import { createAppContainer } from "../../../infrastructure/container.js";
import { translate } from "../../ui/i18n.js";
import { ActionResult } from "../../types.js";

export async function planValidateAction(spec?: string, taskId?: string): Promise<ActionResult> {
  const container = createAppContainer();
  
  const config = container.configService.loadConfig();
  const lang = config?.language || "en";

  let specName = spec;

  if (!specName) {
    const specs = container.listSpecsUseCase.execute();

    if (specs.length === 0) {
      console.error(translate("err_no_specs_run", lang));
      process.exitCode = 1;
      return { success: false };
    }

    specName = await select({
      message: translate("validate_select_spec", lang),
      choices: [
        { name: translate("menu_back", lang), value: "back" },
        ...specs.map((s) => ({ name: s.name, value: s.name }))
      ],
    });

    if (specName === "back") {
      return { back: true };
    }
  }

  const useCase = container.validatePlanUseCase;
  const result = useCase.execute(specName as string, taskId);

  switch (result.kind) {
    case "not-initialized":
      console.error(translate("err_not_initialized", lang));
      process.exitCode = 1;
      return { success: false };
    case "spec-not-found":
      console.error(translate("err_tasks_dir_not_found", lang, { spec: specName }));
      process.exitCode = 1;
      return { success: false };
    case "invalid":
      console.error(translate("plan_err_validation_failed", lang, { spec: specName }));
      for (const err of result.errors) {
        console.error(`  - ${err}`);
      }
      console.error(translate("plan_err_fix_instructions", lang));
      process.exitCode = 1;
      return { success: false };
    case "valid":
      console.log(translate("validate_success", lang, { spec: specName }));
      return { success: true };
  }
}

export function registerPlanValidateCommand(plan: Command): void {
  plan
    .command("validate [spec] [taskId]")
    .description("Validate the JSON tasks generated by the AI agent")
    .action(async (spec?: string, taskId?: string) => {
      await planValidateAction(spec, taskId);
    });
}
